// ─────────────────────────────────────────────────────────────────────────────
// narrativeTemplates.ts — Career Compass v2 개인화 레이어
//
// mainType → subtype 으로 한 단계 더 내려가, 결과지 4섹션 중 1·2·3을 구성한다.
//   • core            : "지금 고민의 핵심" — 유형 설명이 아니라 *사용자가 느끼는 감각*. 1~2문장.
//   • monthlyApproach : "이번 달 접근 방식" — subtype이 '무엇을', readinessLevel이 '어느 강도로'. 1~2문장.
//   • weeklyMove      : "이번 주 한 수" — 1문장, 구체적 행동.
//   • blended         : subtypeConfidence < 0.15 일 때 쓰는 혼합 core (주요 조합만).
//
// 톤 원칙(전체 공통):
//   - "당신은 부족하다"가 아니라 "지금은 이 조건이 갖춰지지 않은 상태"로.
//   - 되돌려 말하기(앵무새) 금지 — 답을 나열하지 말고, 그 답들이 가리키는 *구조*를 읽어준다.
//   - reframe 화법: "X가 약한 게 아니라, Y이다."
//
// 소비처: resultContextEngine.ts (미작성)에서
//   narrativeTemplates[mainType].subtypes[primarySubtype] 로 접근,
//   confidence < 0.15면 narrativeTemplates[mainType].blended[`${a}+${b}`] 사용.
// ※ 컨텍스트 스펙은 subtype을 mainType 직속 키로 두지만, 타입 안전을 위해 subtypes/blended로
//   분리한다(소비처 코드가 아직 없어 자유롭게 결정). 접근 경로만 위와 같이 맞추면 된다.
// ─────────────────────────────────────────────────────────────────────────────

// readinessLevel — '행동 강도'만 담당 (getReadinessLevel 결과). 정본은 careerCompass.ts.
//   pause/reflect_only/tiny_test/structured_test/commitment_test
import type { ReadinessLevel } from '../types/careerCompass.ts';
export type { ReadinessLevel };

export interface SubtypeNarrative {
  core: string;
  monthlyApproach: Partial<Record<ReadinessLevel, string>>;
  weeklyMove: Partial<Record<ReadinessLevel, string>>;
}

export interface MainTypeNarrativeTemplate {
  subtypes: Record<string, SubtypeNarrative>;
  /** secondary subtype 키 → primary core 뒤에 덧붙일 한 절(혼합 시). core를 통째로
   *  바꾸지 않고 primary의 따뜻한 core를 유지한 채 secondary 뉘앙스만 더해, 핵심이 plan과 어긋나지 않게. */
  blendNote: Record<string, string>;
}

